"use client";

import {
  Check,
  Code2,
  Copy,
  Download,
  FileArchive,
  GitCompare,
  Loader2,
  Pencil,
  Save,
  X,
} from "lucide-react";
import { diffLines } from "diff";
import JSZip from "jszip";
import { useEffect, useMemo, useState } from "react";
import { toPlaywright } from "@/lib/quality";
import type { AppSpec, QualityReport } from "@/lib/types";
import { download, downloadBlob, safeFilename } from "@/lib/utils";

export function CodePanel({
  code,
  streaming,
  appName,
  spec,
  report,
  previousCode,
  saving,
  onSaveCode,
}: {
  code: string;
  streaming: boolean;
  appName: string;
  spec: AppSpec | null;
  report: QualityReport | null;
  previousCode: string | null;
  saving: boolean;
  onSaveCode: (code: string) => Promise<void>;
}) {
  const [copied, setCopied] = useState(false);
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(code);
  const [showDiff, setShowDiff] = useState(false);
  const [zipping, setZipping] = useState(false);
  const [editError, setEditError] = useState<string | null>(null);

  useEffect(() => {
    if (!editing) setDraft(code);
  }, [code, editing]);

  const lines = code ? code.split("\n") : [];
  const bytes = new TextEncoder().encode(code).length;

  const diff = useMemo(
    () => (previousCode ? diffLines(previousCode, code) : []),
    [previousCode, code],
  );
  const added = diff.reduce(
    (sum, part) => sum + (part.added ? part.value.split("\n").length - 1 : 0),
    0,
  );
  const removed = diff.reduce(
    (sum, part) => sum + (part.removed ? part.value.split("\n").length - 1 : 0),
    0,
  );

  async function copy() {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      // clipboard may be unavailable in some contexts
    }
  }

  async function saveEdit() {
    if (saving) return;
    if (!/<html[\s>]/i.test(draft)) {
      setEditError("代码需要是完整的 HTML 文档。");
      return;
    }
    setEditError(null);
    try {
      await onSaveCode(draft);
      setEditing(false);
    } catch (err) {
      setEditError(err instanceof Error ? err.message : "保存失败，请重试。");
    }
  }

  async function downloadZip() {
    setZipping(true);
    try {
      const zip = new JSZip();
      zip.file("index.html", code);
      if (report) {
        zip.file(
          "quality-report.json",
          JSON.stringify(
            { app: appName, score: report.score, passed: report.passed, report },
            null,
            2,
          ),
        );
      }
      if (spec) {
        zip.file("tests/app.spec.ts", toPlaywright(spec));
      }
      zip.file(
        "README.md",
        `# ${appName}\n\nGenerated by VibeCheck.\n\n- Quality score: ${
          report ? `${report.score}/100` : "N/A"
        }\n- Gate: ${report?.passed ? "passed" : "not passed"}\n\nOpen \`index.html\` in a browser.\n`,
      );
      const blob = await zip.generateAsync({ type: "blob" });
      downloadBlob(`${safeFilename(appName)}.zip`, blob);
    } catch {
      // ignore zip errors
    } finally {
      setZipping(false);
    }
  }

  if (!code) {
    return (
      <div className="flex h-full flex-col items-center justify-center gap-3 p-8 text-center">
        <div className="flex h-12 w-12 items-center justify-center rounded-2xl border border-line bg-panel">
          <Code2 className="h-5 w-5 text-faint" />
        </div>
        <p className="text-sm text-muted">还没有代码</p>
        <p className="max-w-xs text-xs leading-relaxed text-faint">
          生成应用后，这里会展示完整的单文件 HTML。代码是流式返回的。
        </p>
      </div>
    );
  }

  return (
    <div className="flex h-full flex-col">
      <div className="flex flex-wrap items-center gap-1.5 border-b border-line px-3 py-2">
        <span className="rounded-md border border-line bg-panel2 px-2 py-1 font-mono text-[10px] text-muted">
          index.html
        </span>
        <span className="text-[10px] text-faint">
          {(bytes / 1024).toFixed(1)}KB · {lines.length} 行
        </span>
        {streaming && (
          <span className="inline-flex items-center gap-1 text-[10px] text-accent">
            <Loader2 className="h-3 w-3 animate-spin" />
            生成中
          </span>
        )}
        <div className="ml-auto flex flex-wrap items-center gap-1">
          {!editing ? (
            <button
              onClick={() => {
                setDraft(code);
                setEditing(true);
              }}
              className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink"
            >
              <Pencil className="h-3 w-3" />
              编辑
            </button>
          ) : (
            <>
              <button
                onClick={saveEdit}
                disabled={saving}
                className="inline-flex items-center gap-1 rounded-md border border-accent/30 bg-accent/10 px-2 py-1 text-[11px] text-accent transition hover:bg-accent/15 disabled:opacity-50"
              >
                {saving ? <Loader2 className="h-3 w-3 animate-spin" /> : <Save className="h-3 w-3" />}
                保存并验收
              </button>
              <button
                onClick={() => {
                  setEditing(false);
                  setDraft(code);
                  setEditError(null);
                }}
                className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink"
              >
                <X className="h-3 w-3" />
                取消
              </button>
            </>
          )}
          {previousCode && (
            <button
              onClick={() => setShowDiff(true)}
              className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink"
            >
              <GitCompare className="h-3 w-3" />
              对比上一版
            </button>
          )}
          <button
            onClick={downloadZip}
            disabled={zipping}
            className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink disabled:opacity-50"
          >
            {zipping ? <Loader2 className="h-3 w-3 animate-spin" /> : <FileArchive className="h-3 w-3" />}
            下载 ZIP
          </button>
          <button
            onClick={copy}
            className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink"
          >
            {copied ? <Check className="h-3 w-3 text-accent" /> : <Copy className="h-3 w-3" />}
            {copied ? "已复制" : "复制"}
          </button>
          <button
            onClick={() => download(`${safeFilename(appName)}.html`, code, "text/html;charset=utf-8")}
            className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] text-muted transition hover:bg-panel2 hover:text-ink"
          >
            <Download className="h-3 w-3" />
            下载
          </button>
        </div>
      </div>

      {editing ? (
        <div className="flex min-h-0 flex-1 flex-col bg-[#07080b]">
          <textarea
            value={draft}
            onChange={(e) => setDraft(e.target.value)}
            spellCheck={false}
            className="min-h-0 flex-1 resize-none bg-[#07080b] p-3 font-mono text-[11.5px] leading-5 text-ink/90 outline-none"
          />
          <div className="flex items-center gap-2 border-t border-line px-3 py-2">
            <span className="text-[10px] text-faint">保存后会重新运行质量门禁，生成新版本。</span>
            {editError && <span className="text-[10px] text-danger">{editError}</span>}
          </div>
        </div>
      ) : (
        <div className="min-h-0 flex-1 overflow-auto scrollbar-thin bg-[#07080b]">
          <div className="flex min-h-full font-mono text-[11.5px] leading-5">
            <div className="select-none border-r border-line/50 bg-panel/40 px-3 py-3 text-right tabular-nums text-faint">
              {lines.map((_, i) => (
                <div key={i}>{i + 1}</div>
              ))}
            </div>
            <pre className="min-w-0 flex-1 overflow-x-auto px-3 py-3 text-ink/90">
              <code>{code}</code>
            </pre>
          </div>
        </div>
      )}

      {showDiff && previousCode && (
        <div
          className="fixed inset-0 z-[60] flex items-center justify-center bg-black/70 p-4 backdrop-blur-sm"
          onClick={() => setShowDiff(false)}
        >
          <div
            className="flex h-[80vh] w-full max-w-3xl flex-col rounded-2xl border border-line bg-panel"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex h-11 shrink-0 items-center gap-2 border-b border-line px-4">
              <GitCompare className="h-4 w-4 text-accent" />
              <span className="text-xs font-medium">版本对比</span>
              <span className="text-[10px] text-accent">+{added}</span>
              <span className="text-[10px] text-danger">-{removed}</span>
              <button
                onClick={() => setShowDiff(false)}
                className="ml-auto rounded-md p-1 text-muted hover:bg-panel2 hover:text-ink"
                aria-label="关闭"
              >
                <X className="h-4 w-4" />
              </button>
            </div>
            <div className="min-h-0 flex-1 overflow-auto scrollbar-thin bg-[#07080b] p-3 font-mono text-[11px] leading-5">
              {diff.map((part, i) => {
                const prefix = part.added ? "+" : part.removed ? "-" : " ";
                const cls = part.added
                  ? "bg-accent/10 text-accent"
                  : part.removed
                    ? "bg-danger/10 text-danger"
                    : "text-muted";
                return part.value.split("\n").map((line, j) => {
                  if (line === "" && j === part.value.split("\n").length - 1) return null;
                  return (
                    <div key={`${i}-${j}`} className={`whitespace-pre-wrap px-1 ${cls}`}>
                      {prefix} {line}
                    </div>
                  );
                });
              })}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
